/**
 * The site's own theme, as the `globalCss` block the compiler folds away.
 *
 * `barq-ui init` writes exactly this into a project, and this is the same
 * emitter pointed at the site's own choices. Generated rather than hand-typed
 * because the values are the registry's, and checked in rather than produced at
 * build time because it is the project's file to edit — which is the contract
 * the CLI states.
 *
 * ```
 * bun run tools/emit-theme.ts
 * ```
 *
 * The runtime `installTheme` is the OTHER half, for an application that
 * switches theme while it is running. The site does not: only the designer's
 * preview does, and that one scopes its rules to the preview element.
 */

import { writeFileSync } from "node:fs";
import { join } from "node:path";

import { themeCss } from "../../ui/src/theme/install.ts";

/**
 * shadcn's `DEFAULT_CONFIG` for the base and the radius, and their SITE's own
 * blue chart ramp: `app/globals.css` overrides `--chart-1` to
 * `--color-blue-300` through `800`, while the greyscale ramp `base-colors.ts`
 * gives `neutral` is what a consumer's own app starts from.
 */
const css = themeCss({
  base: "neutral",
  chart: "blue",
  fonts: {
    sans: '"Geist Variable", sans-serif',
    mono: '"Geist Mono Variable", monospace',
  },
});

const source = [
  "/**",
  " * The site's theme, folded into a stylesheet at build time.",
  " *",
  " * GENERATED by `tools/emit-theme.ts`. The compiler turns this block into a",
  " * rule in the sheet the document links, so the page arrives themed rather",
  " * than being themed by a script — no flash, and nothing of the call left in",
  " * the bundle.",
  " *",
  " * The designer's preview is the one thing that still themes at run time, and",
  " * it scopes its rules to itself.",
  " */",
  "",
  'import { globalCss } from "@barqjs/css";',
  "",
  "globalCss`",
  css,
  "`;",
  "",
].join("\n");

writeFileSync(join(import.meta.dir, "../src/theme.ts"), source);
console.log(`wrote src/theme.ts (${String(css.length)} bytes of CSS)`);
