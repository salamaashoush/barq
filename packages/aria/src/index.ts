/**
 * `@barqjs/aria` — accessible interactions, state and headless components.
 *
 * Every module is an entry point of its own as well as being re-exported here,
 * so `@barqjs/aria/listbox` and a tree-shaken import from the root cost the
 * same. The re-exports are named rather than `export *`: a name defined in two
 * modules is silently dropped from a star export, and this package has enough
 * surface for that to happen without anyone noticing.
 *
 * Two things separate it from `react-aria`, which it was studied from:
 *
 * - **Names carry no `use` prefix.** A component here runs once and there is no
 *   rules-of-hooks to signal, so `press()`, `button()` and `listBox()` are what
 *   they are called.
 * - **Collections are data-driven.** `items` plus a render function, rather
 *   than a first pass that renders the children to find out what they declare.
 *   See `collections.ts`.
 */

