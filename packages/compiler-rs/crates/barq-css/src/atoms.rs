//! One class per declaration, and the merge key that makes passing order win.
//!
//! The same semantics as `@barqjs/css`'s runtime, and deliberately the same
//! NAMES: a class is `a-<property>[-<conditionHash>]_<valueHash>`, so a block
//! this compiles and a block the runtime built for a value only known at run
//! time dedupe against each other instead of emitting the rule twice.
//!
//! That parity is why the hash here is FNV-1a over 32 bits with no padding,
//! rather than the 64-bit one a scoped block's class uses: it is
//! `Math.imul`-shaped so a four-line JavaScript function can produce the same
//! answer, and it is iterated over UTF-16 code units because `charCodeAt` is.

// `SHORTHANDS`, `UNEXPANDABLE`, `UNITLESS` and `DISPLACES`, generated by
// `build.rs` from `@barqjs/css`'s own source. A property one hand-kept copy
// has and the other lacks is a declaration with two spellings: `fillOpacity:
// 0.5` is `0.5` to the side that lists it and `0.5px` to the side that does
// not.
include!(concat!(env!("OUT_DIR"), "/css_tables.rs"));

pub fn unexpandable(property: &str) -> bool {
    UNEXPANDABLE.binary_search(&property).is_ok()
}

pub fn is_unitless(property: &str) -> bool {
    UNITLESS.binary_search(&property).is_ok()
}

/// Every capital gets a dash, a leading one included, so `WebkitLineClamp` is
/// `-webkit-line-clamp`. `ms` is the one prefix written in lower case.
pub fn kebab(property: &str) -> String {
    if property.starts_with("--") {
        return property.to_string();
    }
    let mut dashed = String::with_capacity(property.len() + 4);
    for character in property.chars() {
        if character.is_ascii_uppercase() {
            dashed.push('-');
        }
        dashed.push(character);
    }
    let lowered = dashed.to_lowercase();
    if lowered.starts_with("ms-") { format!("-{lowered}") } else { lowered }
}

/// A bare number is `px` unless the property counts. `0` is unitless in every
/// property, which is what CSS itself says, and a custom property takes the
/// number as written: nothing here knows what reads `--columns`.
///
/// `raw` is the text JavaScript prints the number as, which is [`number_text`].
pub fn number_value(property: &str, raw: &str) -> String {
    if raw == "0" || property.starts_with("--") || is_unitless(property) {
        raw.to_string()
    } else {
        format!("{raw}px")
    }
}

/// A number as the declaration value it is, or `None` when it is not finite:
/// the runtime declares nothing for `NaN` and the infinities.
pub fn number_declaration(property: &str, value: f64) -> Option<String> {
    value.is_finite().then(|| number_value(property, &number_text(value)))
}

/// FNV-1a over 32 bits, base 36, matching `@barqjs/css`'s `hash` minus its
/// leading marker. Iterated over UTF-16 code units because `charCodeAt` is.
pub fn hash32(text: &str) -> String {
    let mut value: u32 = 0x811c_9dc5;
    for unit in text.encode_utf16() {
        value ^= u32::from(unit);
        value = value.wrapping_mul(0x0100_0193);
    }
    base36(value)
}

fn base36(mut value: u32) -> String {
    const ALPHABET: &[u8; 36] = b"0123456789abcdefghijklmnopqrstuvwxyz";
    if value == 0 {
        return "0".to_string();
    }
    let mut digits = Vec::new();
    while value > 0 {
        digits.push(ALPHABET[(value % 36) as usize]);
        value /= 36;
    }
    digits.reverse();
    String::from_utf8(digits).expect("base36 alphabet is ASCII")
}

/// `JSON.stringify` over a flat object of strings and numbers.
///
/// Spelled out because the token group's name is a hash of it and
/// `@barqjs/css` computes that hash from `JSON.stringify(tokens)`. Anything
/// that formatted one byte differently would name the same tokens two things.
pub fn json_object(entries: &[(String, TokenValue)]) -> String {
    let mut out = String::from("{");
    for (index, (key, value)) in entries.iter().enumerate() {
        if index > 0 {
            out.push(',');
        }
        json_string(key, &mut out);
        out.push(':');
        match value {
            TokenValue::Text(text) => json_string(text, &mut out),
            // `JSON.stringify` has no spelling for a number that is not finite.
            TokenValue::Number(number) if !number.is_finite() => out.push_str("null"),
            TokenValue::Number(number) => out.push_str(&number_text(*number)),
        }
    }
    out.push('}');
    out
}

/// What `String(value)` prints for a number: ECMAScript's `Number::toString`.
///
/// The shortest digits that read back as the same double, laid out by the
/// specification's own four cases. Rust's `{}` finds the same digits and never
/// switches to an exponent, so `1e21` and `1e-7` would be spelled two ways.
pub fn number_text(value: f64) -> String {
    if value.is_nan() {
        return "NaN".to_string();
    }
    if value == 0.0 {
        return "0".to_string();
    }
    if value.is_infinite() {
        return if value > 0.0 { "Infinity" } else { "-Infinity" }.to_string();
    }
    let scientific = format!("{:e}", value.abs());
    let (mantissa, exponent) = scientific.split_once('e').unwrap_or((&scientific, "0"));
    let digits: String = mantissa.chars().filter(char::is_ascii_digit).collect();
    let point = exponent.parse::<i32>().unwrap_or(0) + 1;
    let count = i32::try_from(digits.len()).unwrap_or(i32::MAX);
    let zeros = |n: i32| "0".repeat(usize::try_from(n).unwrap_or(0));
    let body = if count <= point && point <= 21 {
        format!("{digits}{}", zeros(point - count))
    } else if 0 < point && point <= 21 {
        let (whole, fraction) = digits.split_at(usize::try_from(point).unwrap_or(0));
        format!("{whole}.{fraction}")
    } else if -6 < point && point <= 0 {
        format!("0.{}{digits}", zeros(-point))
    } else {
        let power = point - 1;
        let sign = if power < 0 { '-' } else { '+' };
        let (lead, rest) = digits.split_at(1);
        let rest = if rest.is_empty() { String::new() } else { format!(".{rest}") };
        format!("{lead}{rest}e{sign}{}", power.abs())
    };
    if value < 0.0 { format!("-{body}") } else { body }
}

#[derive(Debug, Clone, PartialEq)]
pub enum TokenValue {
    Text(String),
    Number(f64),
}

fn json_string(text: &str, out: &mut String) {
    out.push('"');
    for character in text.chars() {
        match character {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            '\u{8}' => out.push_str("\\b"),
            '\u{c}' => out.push_str("\\f"),
            control if control < ' ' => out.push_str(&format!("\\u{:04x}", control as u32)),
            other => out.push(other),
        }
    }
    out.push('"');
}

/// The custom property a token becomes, and the `var()` that reads it.
///
/// The group suffix is a hash of the whole token object, so two files declaring
/// the same tokens share them and two whose `brand` differs do not collide —
/// and neither has to know the file it is in.
pub fn token_property(group: &str, token: &str) -> String {
    let safe: String = token
        .chars()
        .map(|c| if c.is_alphanumeric() || c == '_' || c == '-' { c } else { '-' })
        .collect();
    format!("--{safe}-{group}")
}

/// A token's property under the name the author gave it, for `globalVars`.
///
/// No group suffix, which is the whole point: an application's own
/// `:root { --primary: … }` is heard, and a design system's tokens are a
/// published contract rather than a closed set.
pub fn global_property(token: &str) -> String {
    let safe: String = token
        .chars()
        .map(|c| if c.is_alphanumeric() || c == '_' || c == '-' { c } else { '-' })
        .collect();
    format!("--{safe}")
}

/// The custom property a dynamic declaration reads.
///
/// Derived from the property alone, so the compiler and `@barqjs/css`'s runtime
/// agree without either knowing what the other saw — the same reason an atom's
/// class name carries its own merge key.
pub fn dynamic_var(property: &str) -> String {
    format!("--{property}-{}", hash32(property))
}

/// A fallback list as the same declaration repeated, best LAST.
///
/// CSS's own mechanism: a browser keeps the last declaration it understands, so
/// preference order is the reverse of source order.
pub fn fallback(property: &str, values: &[String]) -> String {
    values.iter().rev().cloned().collect::<Vec<_>>().join(&format!(";{property}:"))
}

/// CSS's own 1/2/3/4 box rule, or 1/2 for a two-longhand shorthand.
///
/// `!important` is the declaration's and not a side's, so it is taken off
/// before the values are counted and written back onto every longhand.
pub fn expand(property: &str, value: &str) -> Option<Vec<(String, String)>> {
    let longhands = SHORTHANDS.iter().find(|(name, _)| *name == property).map(|(_, list)| *list)?;
    let (body, important) = match unimportant(value) {
        Some(body) => (body, " !important"),
        None => (value, ""),
    };
    let values =
        if property == "border-radius" { radii(body)? } else { sides(longhands.len(), body)? };
    Some(
        longhands
            .iter()
            .zip(values)
            .map(|(name, own)| ((*name).to_string(), format!("{own}{important}")))
            .collect(),
    )
}

/// What JavaScript's `\s` matches, which is not what `char::is_whitespace`
/// does: it takes U+FEFF and leaves U+0085.
fn is_js_space(character: char) -> bool {
    matches!(
        character,
        '\t' | '\n' | '\u{b}' | '\u{c}' | '\r' | ' ' | '\u{a0}' | '\u{1680}' | '\u{2000}'
            ..='\u{200a}'
                | '\u{2028}'
                | '\u{2029}'
                | '\u{202f}'
                | '\u{205f}'
                | '\u{3000}'
                | '\u{feff}'
    )
}

/// A value with a trailing `!important` taken off, or `None` when it has none.
fn unimportant(value: &str) -> Option<&str> {
    let end = value.trim_end_matches(is_js_space);
    let word = end.len().checked_sub("important".len())?;
    if !end.is_char_boundary(word) || !end[word..].eq_ignore_ascii_case("important") {
        return None;
    }
    let bang = end[..word].trim_end_matches(is_js_space).strip_suffix('!')?;
    Some(bang.trim_end_matches(is_js_space))
}

fn sides(count: usize, value: &str) -> Option<Vec<String>> {
    let parts = split_values(value);
    let part = |index: usize| parts[index].clone();
    if count == 2 {
        return match parts.len() {
            1 => Some(vec![part(0), part(0)]),
            2 => Some(parts),
            _ => None,
        };
    }
    match parts.len() {
        1 => Some(vec![part(0), part(0), part(0), part(0)]),
        2 => Some(vec![part(0), part(1), part(0), part(1)]),
        3 => Some(vec![part(0), part(1), part(2), part(1)]),
        4 => Some(parts),
        _ => None,
    }
}

/// `border-radius` is two box shorthands either side of a slash, the
/// horizontal radii and the vertical, and each corner takes one of each.
fn radii(value: &str) -> Option<Vec<String>> {
    let mut depth = 0i32;
    let slash = value.char_indices().find_map(|(index, character)| {
        match character {
            '(' => depth += 1,
            ')' => depth -= 1,
            '/' if depth == 0 => return Some(index),
            _ => {}
        }
        None
    });
    let Some(slash) = slash else { return sides(4, value) };
    let horizontal = sides(4, &value[..slash])?;
    let vertical = sides(4, &value[slash + 1..])?;
    Some(
        horizontal.iter().zip(&vertical).map(|(across, down)| format!("{across} {down}")).collect(),
    )
}

/// Top-level whitespace split, so `calc(1px + 2px)` and `var(--a, b)` stay whole.
fn split_values(value: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut depth = 0i32;
    let mut start = 0usize;
    let bytes = value.as_bytes();
    for index in 0..=bytes.len() {
        match bytes.get(index) {
            Some(b'(') => depth += 1,
            Some(b')') => depth -= 1,
            None | Some(b' ' | b'\t' | b'\n' | b'\r' | 0x0c) if depth == 0 => {
                if index > start {
                    out.push(value[start..index].to_string());
                }
                start = index + 1;
            }
            _ => {}
        }
    }
    out
}

/// Whether a value stays inside the declaration it is written into.
///
/// A value reaches the sheet as text, and one that closes a brace it did not
/// open ends the rule and starts another: `red;} body{display:none` is a
/// stylesheet, not a colour. The runtime refuses it, so a literal has to be
/// refused here too or the two disagree about which class an object makes.
/// The one `;` allowed is the one [`fallback`] writes, between two
/// declarations of the same property.
pub fn contained(property: &str, value: &str) -> bool {
    let bytes = value.as_bytes();
    let mut nested = 0i32;
    let mut braces = 0i32;
    let mut index = 0usize;
    while index < bytes.len() {
        match bytes[index] {
            b'\\' => {
                index += 1;
                if index >= bytes.len() {
                    return false;
                }
            }
            quote @ (b'"' | b'\'') => match string_end(bytes, index, quote) {
                Some(close) => index = close,
                None => return false,
            },
            b'/' if bytes.get(index + 1) == Some(&b'*') => match value[index + 2..].find("*/") {
                Some(close) => index += 2 + close + 1,
                None => return false,
            },
            b'(' | b'[' => nested += 1,
            b')' | b']' => {
                nested -= 1;
                if nested < 0 {
                    return false;
                }
            }
            b'{' => braces += 1,
            b'}' => {
                braces -= 1;
                if braces < 0 {
                    return false;
                }
            }
            b';' if nested == 0 && braces == 0 => {
                let next = &value[index + 1..];
                if !next.strip_prefix(property).is_some_and(|rest| rest.starts_with(':')) {
                    return false;
                }
                index += property.len() + 1;
            }
            _ => {}
        }
        index += 1;
    }
    nested == 0 && braces == 0
}

/// The index of the quote closing the string that opens at `open`.
fn string_end(bytes: &[u8], open: usize, quote: u8) -> Option<usize> {
    let mut index = open + 1;
    while index < bytes.len() {
        match bytes[index] {
            b'\\' => index += 1,
            b'\n' => return None,
            byte if byte == quote => return Some(index),
            _ => {}
        }
        index += 1;
    }
    None
}

/// How an atom is ORDERED against another atom, and nothing more.
///
/// Not a cascade layer, and this used to be one. Layers gave ordering across
/// modules and took away the thing atoms exist for: a layered rule loses to an
/// UNLAYERED one whatever the specificity, so an application's `* { margin: 0 }`
/// beat every `margin` atom on the page — measured in a browser, every margin
/// and padding computing to `0px`. Layering the reset too would have fixed that
/// case and made any plain CSS the application writes beat every atom, which is
/// backwards.
///
/// Specificity does almost all of it on its own: `.a-color_x` is 0-1-0,
/// `.a-color-h_y:hover` is 0-2-0, `.a-content_z::before` is 0-1-1. The only
/// pair specificity cannot separate is a base against the same property under
/// an at-rule, because `@media` adds none — so a module emits its atoms in tier
/// order and that pair is decided.
///
/// Ordering ACROSS modules is not needed and never was: two atoms conflict only
/// when they are merged, merging happens in one `atoms` call, and one call is
/// in one module.
/// `Descendant` comes FIRST, and it is the one tier order decides rather than
/// specificity: a rule a parent writes about its children — `& > *`, `& svg` —
/// and a rule the child writes about itself are both one class. Measured in a
/// browser, a field saying `& > * { width: 100% }` took a label's own
/// `width: fit-content` away and stretched it across the row.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub enum Tier {
    Descendant,
    Base,
    Select,
    Element,
    Media,
}

impl Tier {
    /// The tier's name, for a diagnostic and for the ordering pass's tests.
    ///
    /// A tier is NOT a cascade layer and must not become one. It is a
    /// tie-breaker on top of specificity — CSS decides by specificity first and
    /// order second — and a layer overrides specificity outright. Measured in a
    /// browser: emitting each tier into `@layer barq.ui.<tier>` moved 289
    /// computed values on the gallery, because a parent's
    /// `[data-variant="destructive"] &` at 0-2-0 stopped beating the child's own
    /// 0-1-0 the moment the two sat in different sub-layers. Ordering the rules
    /// moves 8, and every one of them is a rule under an at-rule that was
    /// losing to a base rule another module emitted after it.
    pub fn as_str(self) -> &'static str {
        match self {
            Tier::Descendant => "descendant",
            Tier::Base => "base",
            Tier::Select => "select",
            Tier::Element => "element",
            Tier::Media => "media",
        }
    }
}

/// A condition path, joined. `@media …` outside, `:hover` inside.
///
/// NUL, because it cannot appear in a selector or an at-rule prelude, and
/// because `@barqjs/css` joins with the same byte — the hash is over the joined
/// text, so the two implementations agree without either parsing the other's
/// separator.
pub const NEST: char = '\u{0}';

/// The tier a condition wins in, taken from its MOST specific part: a rule
/// conditioned on both a media query and a pseudo-class is a media rule.
fn tier_of(condition: &str) -> Tier {
    if condition == "default" {
        return Tier::Base;
    }
    if !about_self(condition) {
        return Tier::Descendant;
    }
    let parts = || condition.split(NEST);
    if parts().any(|part| part.starts_with('@')) {
        Tier::Media
    } else if parts().any(|part| part.contains("::")) {
        Tier::Element
    } else {
        Tier::Select
    }
}

/// A selector list, split at the commas that separate its branches.
///
/// Depth-aware, because `:is(a, b)` and `:not(a, b)` both carry a comma that
/// separates nothing.
fn branches(part: &str) -> Vec<&str> {
    let mut out = Vec::new();
    let mut depth = 0i32;
    let mut start = 0usize;
    for (index, character) in part.char_indices() {
        match character {
            '(' | '[' => depth += 1,
            ')' | ']' => depth -= 1,
            ',' if depth == 0 => {
                out.push(part[start..index].trim());
                start = index + 1;
            }
            _ => {}
        }
    }
    out.push(part[start..].trim());
    out
}

/// One branch of a condition, applied to one selector built so far.
///
/// EVERY branch of a list gets the treatment, and that is the whole reason this
/// is a function. `"[data-expanded], &[data-open]"` used to be substituted as
/// one string: the `&` in the second branch matched, so the first branch was
/// left as a bare `[data-expanded]` and the rule painted every element on the
/// page carrying that attribute. Measured in a browser on `@barqjs/ui`'s
/// menubar, where it took an accordion trigger's background. `atoms.ts` joins
/// them the same way.
fn extend(selector: &str, branch: &str) -> String {
    if branch.contains('&') {
        branch.replace('&', selector)
    } else if branch.starts_with(':') || branch.starts_with('[') {
        format!("{selector}{branch}")
    } else {
        format!("{selector} {branch}")
    }
}

/// The selectors a condition's non-at-rule parts build from `seed`.
fn selectors(condition: &str, seed: &str) -> Vec<String> {
    let mut out = vec![seed.to_string()];
    for part in condition.split(NEST).filter(|part| !part.starts_with('@')) {
        out = out
            .iter()
            .flat_map(|selector| {
                branches(part).into_iter().map(move |branch| extend(selector, branch))
            })
            .collect();
    }
    out
}

/// Whether a condition's subject is this element, or something under it.
///
/// A rule a parent writes about its children and a rule the child writes about
/// itself are both one class, so nothing separates them but which came last.
/// The child's own rule is the more specific intent, so the parent's sorts
/// first and loses the tie. `atoms.ts` decides it the same way.
///
/// A list is about a descendant when ANY of its branches is: the rule reaches
/// something under the element, whatever the rest of it does.
fn about_self(condition: &str) -> bool {
    selectors(condition, "&").iter().all(|selector| {
        let at = selector.rfind('&').map_or(0, |index| index + 1);
        let mut depth = 0i32;
        for character in selector[at..].chars() {
            match character {
                '(' | '[' => depth += 1,
                ')' | ']' => depth -= 1,
                ' ' | '>' | '+' | '~' if depth == 0 => return false,
                _ => {}
            }
        }
        true
    })
}

impl Atom {
    /// The rule without the `@layer` wrapper `atom_in` put on it, for a test
    /// assembling a layer by hand.
    #[cfg(test)]
    pub(crate) fn rule_body(&self) -> &str {
        match self.rule.strip_prefix("@layer ") {
            Some(rest) => match rest.find('{') {
                Some(brace) => &rest[brace + 1..self.rule.len() - "@layer ".len() - 1],
                None => &self.rule,
            },
            None => &self.rule,
        }
    }
}

/// One declaration, as a class, a merge key and a rule.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Atom {
    pub class: String,
    /// Everything a later declaration has to replace: the class up to its value.
    pub key: String,
    pub rule: String,
    /// Where this rule sorts against another atom's, within one module.
    pub tier: Tier,
}

pub fn atom(property: &str, condition: &str, value: &str) -> Atom {
    atom_in("", property, condition, value)
}

/// What a class already in a class string merges against.
///
/// An atom carries its property, so `a-color_1n4k2p0` is replaced by any later
/// `color`. A class that is NOT one of ours — an application's own, arriving
/// through a `class` prop — carries no property and has nothing to merge
/// against, so it stands for itself and survives whatever follows it.
pub fn merge_key(class: &str) -> String {
    match class.rfind('_') {
        Some(cut) if class.starts_with("a-") => class[..cut].to_string(),
        _ => class.to_string(),
    }
}

/// The keys an atom takes the place of besides its own: the same axis of the
/// box written the other way, under the same condition.
///
/// `padding-left` and `padding-inline-start` are two properties and one side,
/// so both apply and the stylesheet's order decides, which is whichever was
/// used first. Read off the key, as the merge itself is, so a class string
/// displaces exactly as the object that made it. A key is its property and
/// then, under a condition, a dash and that condition's hash, so one that is
/// not a property outright is tried without its last segment. `atoms.ts` reads
/// it the same way.
pub fn displaced(key: &str) -> Vec<String> {
    let Some(name) = key.strip_prefix("a-") else { return Vec::new() };
    let of = |property: &str| {
        DISPLACES.binary_search_by(|(held, _)| (*held).cmp(property)).ok().map(|at| DISPLACES[at].1)
    };
    let (others, suffix) = match of(name) {
        Some(others) => (others, ""),
        None => match name.rfind('-').and_then(|cut| Some((of(&name[..cut])?, &name[cut..]))) {
            Some(found) => found,
            None => return Vec::new(),
        },
    };
    others.iter().map(|other| format!("a-{other}{suffix}")).collect()
}

/// One atom, merged: it replaces the atom holding its key where that one
/// stood, and takes out whatever it [`displaced`].
///
/// "Keep the last per key" is what makes PASSING order decide instead of the
/// order the rules were written in, and it is the whole of the merge.
pub fn apply(applied: &mut Vec<Atom>, atom: Atom) {
    // A class that is not an atom is its own key and has no property in it.
    if atom.key != atom.class {
        let gone = displaced(&atom.key);
        if !gone.is_empty() {
            applied.retain(|held| !gone.contains(&held.key));
        }
    }
    match applied.iter_mut().find(|slot| slot.key == atom.key) {
        Some(slot) => *slot = atom,
        None => applied.push(atom),
    }
}

/// A declaration as the atoms it is, expanded through any shorthand.
///
/// An unexpandable shorthand is left whole rather than half-expanded: its
/// values go to sub-properties by TYPE, so counting them cannot say which one
/// a value belongs to. A value that would leave its rule is no atoms at all.
pub fn resolve(layer: &str, property: &str, condition: &str, value: &str) -> Vec<Atom> {
    if !contained(property, value) {
        return Vec::new();
    }
    match expand(property, value) {
        Some(longhands) => longhands
            .into_iter()
            .map(|(name, own)| atom_in(layer, &name, condition, &own))
            .collect(),
        None => vec![atom_in(layer, property, condition, value)],
    }
}

/// Two declarations that hash to one class.
///
/// The value's hash is 32 bits, so two values of one property can share a
/// suffix: `width: 40189px` and `width: 797186px` do. The markup would carry
/// one class and the sheet one rule, with nothing anywhere to say the second
/// declaration was lost.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Collision {
    pub class: String,
    pub first: String,
    pub second: String,
}

impl std::fmt::Display for Collision {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(
            f,
            "Two different declarations were given the same class name `{}`: `{}` and `{}`. \
             One class holds one declaration, so the second would be lost. Change how either \
             value is written, for example `8px` to `0.5rem` or `#fff` to `white`, so they get \
             different names.",
            self.class, self.first, self.second
        )
    }
}

/// The atoms a stylesheet already holds, by class.
#[derive(Debug, Default)]
pub struct Emitted {
    rules: std::collections::HashMap<String, String>,
}

impl Emitted {
    /// Whether the atom's rule is new to the sheet, or the [`Collision`] it
    /// makes with a different rule already there under its class.
    pub fn insert(&mut self, atom: &Atom) -> Result<bool, Collision> {
        match self.rules.get(&atom.class) {
            None => {
                self.rules.insert(atom.class.clone(), atom.rule.clone());
                Ok(true)
            }
            Some(held) if *held == atom.rule => Ok(false),
            Some(held) => Err(Collision {
                class: atom.class.clone(),
                first: held.clone(),
                second: atom.rule.clone(),
            }),
        }
    }
}

/// The same, inside a cascade layer.
///
/// For a component LIBRARY, whose rules are meant to lose to an application's.
/// The layer joins the atom's identity through the suffix, because one class
/// name cannot carry a layered rule and an unlayered one.
pub fn atom_in(layer: &str, property: &str, condition: &str, value: &str) -> Atom {
    let name = if let Some(rest) = property.strip_prefix("--") {
        format!("var-{rest}")
    } else {
        property.to_string()
    };
    let key = if condition == "default" {
        format!("a-{name}")
    } else {
        format!("a-{name}-{}", hash32(condition))
    };
    // The suffix hashes the VALUE, and nothing else. The key already carries
    // the property and the condition, so the value is all that is left to tell
    // two atoms of one key apart — and hashing it alone means every atom
    // holding that value ends in the same token, which a compressor reads as a
    // back-reference rather than as noise. `atoms.ts` computes the same name;
    // a compiled call and a runtime one have to agree or one declaration
    // reaches the page as two classes.
    let class = format!(
        "{key}_{}",
        if layer.is_empty() { hash32(value) } else { hash32(&format!("{layer}|{value}")) }
    );
    let declaration = format!("{property}:{value}");
    // At-rules wrap from the outside in; the selector parts all apply to the
    // one class, so they concatenate.
    let seed = format!(".{class}");
    let mut inner =
        if condition == "default" { seed } else { selectors(condition, &seed).join(",") };
    inner = format!("{inner}{{{declaration}}}");
    if condition != "default" {
        for part in condition
            .split(NEST)
            .filter(|part| part.starts_with('@'))
            .collect::<Vec<_>>()
            .iter()
            .rev()
        {
            inner = format!("{part}{{{inner}}}");
        }
    }
    let tier = tier_of(condition);
    if !layer.is_empty() {
        inner = format!("@layer {layer}{{{inner}}}");
    }
    Atom { class, key, rule: inner, tier }
}

